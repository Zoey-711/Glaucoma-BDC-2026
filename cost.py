import argparse
import csv
import io
import json
import time
from pathlib import Path

import numpy as np
import pandas as pd

from src.inference import Predictor
from src.submission import COLUMNS, validate_submission
from src.utils import write_json, sha256


def images(directory):
    return sorted(p for p in Path(directory).rglob('*') if p.suffix.lower() in {'.jpg', '.jpeg', '.png'})


def benchmark_ids(paths, expected_ids):
    mapping = {}
    for name in expected_ids:
        key = name.casefold()
        if key in mapping:
            raise ValueError('Ambiguous case-insensitive submission IDs')
        mapping[key] = name
    try:
        ids = [mapping[p.name.casefold()] for p in paths]
    except KeyError as e:
        raise ValueError('Benchmark sample absent from submission') from e
    if len(set(ids)) != len(ids):
        raise ValueError('Duplicate benchmark filenames; explicit official ID mapping required')
    return ids


def consistency(expected, actual):
    a = expected.set_index('Image_name').loc[actual.Image_name]
    p, q = a.Probability.to_numpy(), actual.Probability.to_numpy()
    bad = (np.abs(p - q) > 1e-3) | (a.Pred_Label.to_numpy() != actual.Pred_Label.to_numpy())
    # Compare full pairwise ordering, including ties (not merely sorted indices).
    ordering = np.sign(p[:, None] - p[None, :]) != np.sign(q[:, None] - q[None, :])
    bad |= ordering.any(axis=1)
    return int(bad.sum())


def main():
    p = argparse.ArgumentParser()
    p.add_argument('submission')
    p.add_argument('pictures_100')
    p.add_argument('pictures_5')
    p.add_argument('--checkpoint', required=True)
    p.add_argument('--device', default='cuda')
    p.add_argument('--precision', choices=['fp32', 'fp16'], default='fp32')
    p.add_argument('--output', default='outputs/cost')
    p.add_argument('--smoke', action='store_true', help='Nonofficial CPU/small sample diagnostic only')
    a = p.parse_args()
    measured, warmup = images(a.pictures_100), images(a.pictures_5)
    if not measured or not warmup:
        raise ValueError('Empty benchmark/warmup directory')
    if not a.smoke and (len(measured) != 100 or len(warmup) != 5):
        raise ValueError('Official benchmark requires exactly 100 measured and 5 warmup images')
    if set(x.resolve() for x in measured) & set(x.resolve() for x in warmup):
        raise ValueError('Warmup and measured images must be separate')
    predictor = Predictor(a.checkpoint, a.device, a.precision, allow_smoke=a.smoke)
    metadata_path = Path(a.submission + '.metadata.json')
    if metadata_path.exists():
        submitted_metadata = json.loads(metadata_path.read_text(encoding='utf-8'))
        if submitted_metadata['checkpoint_sha256'] != predictor.metadata['checkpoint_sha256']:
            raise ValueError('Submission was generated by a different checkpoint')
        if submitted_metadata['precision'] != predictor.precision:
            raise ValueError('Use the same declared precision as submission')
    elif not a.smoke:
        raise ValueError('Missing submission metadata; generate submission using predict.py')
    gpu = predictor.metadata['gpu'] or ''
    if not a.smoke and (predictor.device.type != 'cuda' or 'T4' not in gpu):
        raise ValueError('Official certification requires NVIDIA T4 CUDA; use --smoke for diagnostics')
    all_expected = pd.read_csv(a.submission, dtype={'Image_name': str})
    expected = validate_submission(a.submission, all_expected.Image_name, predictor.threshold)
    ids = benchmark_ids(measured, expected.Image_name)
    out = Path(a.output)
    out.mkdir(parents=True, exist_ok=False)
    with (out / 'warmup.csv').open('w', newline='', encoding='utf-8') as f:
        w = csv.writer(f)
        for x in warmup:
            predictor.predict_one(x, x.name, w, f)
    elapsed, mismatch = [], []
    for repeat in range(3):
        timings = []
        dest = out / f'round_{repeat + 1}.csv'
        with dest.open('w', newline='', encoding='utf-8') as f:
            w = csv.writer(f)
            w.writerow(COLUMNS)
            for x, image_id in zip(measured, ids):
                predictor.synchronize()
                start = time.perf_counter_ns()
                predictor.predict_one(x, image_id, w, f)
                predictor.synchronize()
                timings.append((time.perf_counter_ns() - start) / 1e6)
        elapsed.append(timings)
        actual = validate_submission(dest, ids, predictor.threshold)
        mismatch.append(consistency(expected, actual))
    per_sample = np.asarray(elapsed).mean(axis=0)
    mean = float(per_sample.mean())
    report = {**predictor.metadata, 'official_protocol': not a.smoke,
        'submission_sha256': sha256(a.submission),
        'latency_ms_by_round': elapsed, 'sample_ids': ids, 'per_sample_mean_ms': per_sample.tolist(),
        'mean_ms': mean, 'p95_ms': float(np.percentile(per_sample, 95)),
        'mismatches_by_round': mismatch, 'within_100ms': mean <= 100,
        'passed': not a.smoke and mean <= 100 and not any(mismatch),
        'timing_scope': 'file read through CSV write+flush; CUDA synchronized; OS page cache not cleared'}
    write_json(out / 'report.json', report)
    print(f'[CONCLUSION] samples={len(ids)}, batch=1, rounds=3, mean={mean:.3f}ms, mismatches={mismatch}, precision={a.precision}, official={not a.smoke}')
    if any(mismatch) or (not a.smoke and mean > 100):
        raise SystemExit(1)


if __name__ == '__main__':
    main()
